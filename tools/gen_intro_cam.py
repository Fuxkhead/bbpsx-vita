#!/usr/bin/env python3
"""cam1 of CutsceneCamRigAnim_IntroP1 sampled every 0.25 s -> a C table (game axes: the converter file to game map (-y, -x, z), metres; forward vector).  usage: python3 gen_intro_cam.py <CutsceneCamRigAnim_IntroP1.psa> [out.h]"""
import sys, math, numpy as np
sys.path.insert(0, __import__('os').path.dirname(__import__('os').path.abspath(__file__)))
import convert_hunter as ch
def rotm(roll, pitch, yaw):
    r, p, y = [math.radians(v) for v in (roll, pitch, yaw)]
    sr, cr, sp, cp, sy, cy = math.sin(r), math.cos(r), math.sin(p), math.cos(p), math.sin(y), math.cos(y)
    X = (cp * cy, cp * sy, sp); Y = (sr * sp * cy - cr * sy, sr * sp * sy + cr * cy, -sr * cp); Z = (-(cr * sp * cy + sr * sy), cy * sr - cr * sp * sy, cr * cp)
    return np.array([X, Y, Z]).T
def qm(q):
    x, y, z, w = q
    return np.array([[1-2*(y*y+z*z), 2*(x*y-z*w), 2*(x*z+y*w)], [2*(x*y+z*w), 1-2*(x*x+z*z), 2*(y*z-x*w)], [2*(x*z-y*w), 2*(y*z+x*w), 1-2*(x*x+y*y)]])
def lin(ts, vs, t):
    if t <= ts[0]: return vs[0]
    if t >= ts[-1]: return vs[-1]
    for i in range(len(ts) - 1):
        if ts[i] <= t <= ts[i+1]: return vs[i] + (vs[i+1] - vs[i]) * (t - ts[i]) / (ts[i+1] - ts[i])
C = ch.load_psa(sys.argv[1])[0]; k = C['keys']; fps = C['fps']; nf = C['n']
def bone(f):
    return ch.world_chain(C['bones'], C['parents'], [(k[f][i]['q'], k[f][i]['p']) for i in range(len(C['bones']))])['cam1']
rows = []; t = 0.0
while t <= 37.4001:
    fr = t * fps; f0 = min(int(fr), nf - 1); f1 = min(f0 + 1, nf - 1); u = fr - f0
    q0, p0 = bone(f0); q1, p1 = bone(f1)
    p = np.array(p0) * (1 - u) + np.array(p1) * u; q = np.array(q0) if u < 0.5 else np.array(q1)
    R = qm(q) @ rotm(0, lin([5.367, 10.433, 17.233, 22.0], [-90, -90, -87, -90], t), 0)      # Cam1's own rotation in the sequence: only its pitch matters (roll and yaw cancel at -90)
    fw = R @ np.array([1, 0, 0])
    rows.append((t, -p[1] / 100, -p[0] / 100, p[2] / 100, -fw[1], -fw[0], fw[2])); t += 0.25      # the converter file to game axis map: (x, y, z) -> (-y, -x, z), metres
out = '// generated by gen_intro_cam.py from CutsceneCamRigAnim_IntroP1: cam1 relative to the scene origin (game axes: the converter file to game map (-y, -x, z), metres; forward vector)\nstatic const float IN1_CAM[%d][7] = {\n' % len(rows)
out += ''.join('    {%.3ff,%.3ff,%.3ff,%.3ff,%.4ff,%.4ff,%.4ff},\n' % r for r in rows) + '};\n'
open(sys.argv[2] if len(sys.argv) > 2 else 'intro1_cam.h', 'w').write(out); print(len(rows), 'rows')
